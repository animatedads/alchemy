set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
: "${REXX_BIN:=rexx}"
: "${BRANCH_DAY_SRC:?set BRANCH_DAY_SRC}"
: "${BRANCH_CASH_SRC:?set BRANCH_CASH_SRC}"
: "${BRANCH_CASH_SERVICE_SRC:?set BRANCH_CASH_SERVICE_SRC}"
: "${TELLER_TILL_SRC:?set TELLER_TILL_SRC}"
